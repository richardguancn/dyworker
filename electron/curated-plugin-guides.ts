import { authoringSkill } from './authoring-skills.ts';

/** 原始资料保持不变；这两种插件的实际执行要求改为 DYWorker 本地流程。 */
export function localPluginGuide(pluginId: string, entry: string) {
  if (pluginId === 'plugin-creator') {
    const creator = authoringSkill('plugin');
    if (entry === 'create-plugin') return {
      description: '制作可安装的 DYWorker 本地插件，检查实际功能，不需要连接账号服务。',
      instructions: creator.instructions,
    };
    if (entry === 'update-plugin') return {
      description: '读取并修改用户指定的 DYWorker 本地插件，保留已有功能并验证变更。',
      instructions: `# 修改 DYWorker 本地插件

从用户指定的本地源目录开始，用 read_file 读取 package.json、入口、README.md 和相关资源；路径不明确且当前工作区不能唯一确定时才询问。保留包名、用户数据和未要求修改的功能。不要编辑随应用提供的原始资料或已安装目录；安装目录不是源目录时，先找到源目录，或在工作区复制一份后修改。

按下方本地插件制作要求实现和验证变更。已有验证脚本先运行，补充覆盖本次改动的代表性输入和异常情况；有界面时实际打开检查。用户只要求修改时交付源目录；同时要求安装或重新加载时，只通过当前真实提供的安装能力执行。没有可操作的安装入口时，说明“插件 → DSH 插件 → 安装本地插件”的具体步骤，不编造命令，不宣称已经安装。与同名已安装版本冲突时，先检查应用给出的结果，不自动卸载或删除用户数据。

${creator.instructions}`,
    };
    if (entry === 'prepare-plugin-submission') return {
      description: '检查并整理 DYWorker 本地插件的交付包、说明和验证记录。',
      instructions: `# 整理 DYWorker 本地插件交付包

适用于用户要求打包、整理或准备交付 DYWorker 本地插件。这里的交付是本地文件，不要求连接 OpenAI 账号或在线提交平台。

1. 读取用户指定目录的 package.json、入口、资源、README.md 和现有验证记录，确认名称、版本、用途、依赖、许可和实际入口。未知发布者信息、网址和验证结果不能编造。
2. 按下面的本地插件要求实际验证。发现缺文件、依赖或失败先修复重试；无法解决的缺项写入交付说明，不能称为可用。
3. 在当前工作区单独整理交付目录或压缩包，保留入口、必要资源、许可和说明；不带密钥、个人资料、临时文件或 node_modules。保留原始源目录，不覆盖同名输出。
4. 重新检查最终目录；压缩包需解压到临时目录，检查引用路径，再运行可执行的验证。只报告本次真实完成的检查和未验证范围。
5. README.md 写清用途、安装前提、安装步骤、实际验证结果和限制。用户可通过“插件 → DSH 插件 → 安装本地插件”安装。交付包生成不等于安装、提交审核或公开发布；只有用户要求对应外部操作且当前工具支持时才执行。

${creator.instructions}`,
    };
  }
  if (pluginId === 'plugin-management' && entry === 'plugin-management') return {
    description: '查看、安装、启停、配置或卸载 DYWorker 本地插件，不需要连接账号服务。',
    instructions: `# 管理 DYWorker 本地插件

管理当前 DYWorker 中的插件，不管理 OpenAI 账号；不要求搜索、建议或连接账号服务。先判断用户要查看状态、安装、启停、改配置还是卸载，已明确的对象和动作不重复询问。

## 查看与选择
入口为“插件”。“内置精选”管理随应用提供的工作方法；“DSH 插件”管理可安装的功能插件；“Claude Mods”和“MCP”分别管理对应扩展，不混用不同类型的安装方式。DSH 插件页面的“已安装”列表展示实际状态，点选插件可查看说明与失败原因。发现安装成功但等待所需能力、启动失败或停用时，如实说明，不能当作可用。

## 执行
使用当前环境确实提供的插件管理工具或界面操作能力；调用前检查工具名称、参数和对象编号，不猜造 list_plugins、install_plugin 等工具或命令。没有控制应用的能力时，完成可用的本地资料检查，并给出下面对应的界面步骤；明确需要用户操作的部分，不能声称已执行。不要通过直接编辑应用配置或删除插件目录绕过安装检查。

- 安装本地功能插件：先读取目标目录的 package.json、入口和 README.md，核对文件齐全，再在“插件 → DSH 插件 → 安装本地插件”选择或填写完整目录。检查安装结果及兼容性提示；失败先查具体原因。安装之后再检查列表状态并实际使用功能。
- 启停功能插件：在“插件 → DSH 插件 → 已安装”找到唯一目标，使用该行开关或详情中的“启用插件”“停用插件”。等待保存后刷新核对。需要任务内验证的插件，应在实际适用的任务中检查，不能只看开关。
- 配置功能插件：先读取目标详情、现有配置和插件说明，只修改用户要求的项目。通过页面实际提供的配置入口保存；格式错误或保存失败先修复，成功后重新读取核对。
- 卸载：仅在用户明确要求移除时执行，选中实际已安装的目标并使用页面“卸载”或“卸载插件”，完成后刷新确认已移除。随应用提供的内置插件不能卸载，可按用户要求停用；不擅自删除目录。
- 内置精选：在“插件 → 内置精选”找到目标并使用开关。总开关控制该插件下的所有工作方法，单独停用的工作方法不会因总开关重新打开而恢复。

完成后简洁说明目标、实际变化、验证结果和具体未完成部分。没有真实操作或未读回状态时，只能报告检查结果或操作步骤。`,
  };
  return undefined;
}
